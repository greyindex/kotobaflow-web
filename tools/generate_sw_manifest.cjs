const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { isRuntimePath, omitUnreferencedChunks } = require('./release_files.cjs');
const hash = (text) => crypto.createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex');
// options.checksumsFrom: read the canonical checksum list from the source tree
// when building the manifest of a release package (only files it contains count).
function buildManifest(root, options = {}) {
  const read = (file) => {
    const absolute = path.resolve(root, file);
    if (!absolute.startsWith(path.resolve(root) + path.sep)) throw new Error('Asset outside project');
    const text = fs.readFileSync(absolute, 'utf8');
    if (text.startsWith('version https://git-lfs.github.com/spec/v1'))
      throw new Error('Missing LFS asset: ' + file);
    return text;
  };
  const required = new Set(['index.html']);
  for (const file of ['vocabulary/index.html', 'grammar/index.html', 'textbook/index.html']) {
    if (fs.existsSync(path.join(root, file))) required.add(file);
  }
  for (const tag of read('index.html').matchAll(/<(?:script|link)\b[^>]*>/gi)) {
    const match = tag[0].match(/\b(?:src|href)\s*=\s*["']([^"']+)["']/i);
    if (!match || /^(?:https?:|\/\/|data:)/i.test(match[1])) continue;
    required.add(match[1].split(/[?#]/)[0].replace(/^\.\//, ''));
  }
  // The graph view loads Cytoscape on demand; keep it available offline.
  if (required.has('js/graph-builder.js')) required.add('vendor/cytoscape.min.js');
  const taxonomy = [
    'data/domain_taxonomy.json',
    'data/semantic_tag_taxonomy.json',
    'data/pos.json',
    'data/register.json',
    'data/transitivity.json',
    'data/style.json',
    'data/freq_band.json',
  ];
  if (required.has('js/loader.js')) {
    const index = 'data/vocab_chunks/index.json';
    const vocabulary = JSON.parse(read(index));
    if (vocabulary.version !== 2 || !Array.isArray(vocabulary.chunks) || !vocabulary.chunks.length)
      throw new Error('Invalid startup vocabulary index');
    required.add(index);
    for (const file of vocabulary.chunks) {
      if (!/^[a-f0-9]{64}\.json$/.test(file)) throw new Error('Invalid startup vocabulary chunk');
      required.add('data/vocab_chunks/' + file);
    }
    // First-visit requests precede SW control. Install their dependency closure
    // with the shell, without claiming existing clients or evicting core data.
    taxonomy.forEach((file) => required.add(file));
  }
  const entry = (file) => ({
    url: './' + file,
    sha256: hash(read(file)),
    dynamic: file === 'js/storage-config.js',
  });
  const checksums = path.join(options.checksumsFrom || root, 'resources/checksums/canonical-assets.sha256');
  const dataFiles = fs.existsSync(checksums)
    ? fs
        .readFileSync(checksums, 'utf8')
        .split(/\r?\n/)
        .map((line) => line.match(/^[a-f0-9]{64}\s+(data\/.*\.jsonl?)$/)?.[1])
        .filter(Boolean)
        .filter((file) => !options.checksumsFrom || fs.existsSync(path.join(root, file)))
    : [];
  for (const dir of [
    'data/grammar_chunks',
    'data/vocab_chunks',
    'data/textbook/book_chunks',
    'data/textbook/audio_chunks',
  ]) {
    if (fs.existsSync(path.join(root, dir))) {
      for (const file of fs.readdirSync(path.join(root, dir)).filter((name) => name.endsWith('.json'))) {
        dataFiles.push(dir + '/' + file);
      }
    }
  }
  // Canonical checksums also cover offline build inputs that are not deployed.
  const currentFiles = new Set(dataFiles.filter(isRuntimePath));
  omitUnreferencedChunks(root, currentFiles);
  const data = [...currentFiles].sort().map(entry);
  const optional = [...taxonomy, 'data/grammar_index.json'];
  const manifest = {
    schema: 1,
    version: '',
    required: [...required].sort().map(entry),
    optional: data.filter((e) => optional.includes(e.url.slice(2)) && !required.has(e.url.slice(2))),
    data,
  };
  manifest.version = hash(JSON.stringify(manifest) + read('sw.js')).slice(0, 20);
  return manifest;
}
const source = (manifest) =>
  '// Generated by npm run sw:generate. Do not edit by hand.\nself.JPLearnShellManifest = ' +
  JSON.stringify(manifest, null, 2) +
  ';\n';
if (require.main === module) {
  const root = path.resolve(__dirname, '..'),
    output = path.join(root, 'sw-manifest.js');
  const expected = source(buildManifest(root));
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== expected) {
      console.error('Offline manifest stale: run npm run sw:generate after changing shell/data assets.');
      process.exitCode = 1;
    } else console.log('Offline manifest matches shell and canonical data.');
  } else {
    fs.writeFileSync(output, expected);
    console.log('Generated sw-manifest.js');
  }
}
module.exports = { buildManifest, source, hash };
